'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 const base=process.argv[2],origin=new URL(base).origin;
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
 const ctx=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
 await ctx.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
 const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  const data=await (await page.request.get(new URL('assets/model-directory.json',base).href)).json();
  const expected=data.entries.filter(r=>r.device==='kombi'&&r.brand==='Vaillant');
  assert(expected.length>=30);
  await page.goto(new URL('model-ariza-kodlari.html?device=kombi&brand=Vaillant',base).href,{waitUntil:'networkidle'});
  assert.equal(await page.locator('#modelBrand').inputValue(),'Vaillant');
  while(await page.locator('#modelMore').isVisible())await page.locator('#modelMore').click();
  assert.equal(await page.locator('[data-model-card]').count(),expected.length);
  const labels=await page.locator('[data-model-card] h2').allTextContents();
  assert.equal(new Set(labels.map(x=>x.toLocaleLowerCase('tr'))).size,labels.length);
  assert.equal(await page.locator('[data-model-card][data-verified="true"]').count(),expected.filter(r=>r.verified_model_id).length);
  await page.locator('[data-model-card]').filter({hasText:'26CS/1-5'}).first().click();
  await page.waitForURL(/ecotec-plus-cs1-5-ariza-kodlari\.html/);
  await page.locator('[data-fault-row]').first().waitFor();
  assert(await page.locator('[data-fault-row]').count()>=80);
  assert.equal(await page.locator('#kodlar').count(),1);
  await page.goto(new URL('kucukcekmece-kombi-servisi.html',base).href,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.querySelector('[data-matrix-controls]')?.hidden===false);
  await page.locator('[data-field="brand"]').selectOption('Vaillant');
  const names=await page.locator('[data-field="model"] option').allTextContents();
  assert.equal(names.length,expected.length+2);
  await page.locator('[data-hybrid-matrix] summary').filter({hasText:'Model veya hata kodu'}).click();
  await page.locator('[data-field="model"]').selectOption('vaillant-kombi-ecotec-plus-cs1-5');
  await page.locator('[data-field="code"]').fill('F028');
  await page.locator('[data-matrix-show]').click();
  const guide=page.locator('[data-matrix-result] .hybrid-actions a').first();
  assert.match(await guide.getAttribute('href'),/ecotec-plus-cs1-5-ariza-kodlari\.html#kod-/);
  await guide.click();await page.locator('[data-fault-row]').first().waitFor();assert(await page.locator('[data-fault-row]').count()>=80);
  await page.goto(new URL('index.html#ai-usta',base).href,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>!!window.STUstaWizard&&!!window.STModelDirectory);
  await page.evaluate(()=>STUstaWizard.open('Kombi'));
  await page.locator('#ustaStep [data-choice="error"]').click();
  await page.locator('#ustaBrand').selectOption('Vaillant');
  await page.waitForSelector('#ustaVerifiedModel');
  const aiNames=await page.locator('#ustaVerifiedModel option').allTextContents();
  assert.equal(aiNames.length,expected.length+1);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.equal(errors.length,0,errors.join('; '));
  const report={scope:'Actual local Chromium; official catalogue names and exact code scopes, no provider submissions',vaillant_model_names:expected.length,vaillant_code_linked_variants:expected.filter(r=>r.verified_model_id).length,directory_matrix_ai_share_names:true,duplicate_cards:false,new_plus_table_84_codes:true,model_scoped_code_navigation:true,errors};
  if(process.argv[3])fs.writeFileSync(process.argv[3],JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
 }finally{await ctx.close();await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
